"""Draw the Dragon / Obsidian / Celestial / Astralite tool heads.

LEGIBILITY FIRST, MATERIAL SECOND.

The first attempt at these gave every tier its own head geometry — horns, a
cleaved wedge, a haloed crescent, a pronged fork. Each tier was unmistakable and
the tool TYPE was not: at 16x32 in a bag grid you could not tell a pickaxe from
an axe, which is the only thing the silhouette actually has to communicate. That
was rejected, correctly.

So the silhouette is now fixed per TOOL TYPE and shared across all four tiers,
matching the Bronze->Runite shapes players already read:

    Pickaxe  full-width arched head, two points angled down, centred haft
    Sickle   blade sweeping up-left, over, and down to a point at the right,
             plus the L-shaped side grip on the haft
    Axe      straight poll flush with the haft, weighted blade bulging out to
             one side with a convex cutting edge

Tier identity is carried ONLY by:
  * the metal ramp (unchanged from the rest of the tier art)
  * a 2-3 pixel ornament inset INSIDE the head, never breaking its outline
  * two accent bands on the haft

Masks are authored as explicit pixel grids rather than generated from arcs and
polygons. At this size every pixel is a design decision, and the parametric
version is what produced the amorphous blobs.

Output is a 192x112 sheet per tier laid out on the SAME grid as the base weapon
sheets, so the tool items keep the canonical regions:
    pickaxe Rect2(0, 48, 16, 32)
    sickle  Rect2(32, 48, 16, 32)
    axe     Rect2(112, 48, 16, 32)

    python tools/build_high_tier_tool_art.py
"""
